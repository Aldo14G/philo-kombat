export function composeSprite(pose: PoseName, look: string): string[] {
  const body = POSES[pose];
  const head = LOOKS[look] ?? LOOKS['bald-beard']!;
  return [...head.slice(0, OVERLAY_ROWS), ...body.slice(OVERLAY_ROWS)];
}

/** Rasterize a sprite matrix into an RGBA pixel buffer (scaled ×1). */
export function rasterize(rows: string[], palette: Palette): Uint8ClampedArray<ArrayBuffer> {
  const data = new Uint8ClampedArray(SPRITE_W * SPRITE_H * 4);
  const colors = {
    skin: hex(palette.skin),
    robe: hex(palette.robe),
    accent: hex(palette.accent),
    dark: hex(palette.dark ?? '#1a1420'),
  };
  for (let y = 0; y < Math.min(rows.length, SPRITE_H); y++) {
    const row = rows[y]!;
    for (let x = 0; x < Math.min(row.length, SPRITE_W); x++) {
      const key = CHAR_MAP[row[x]!];
      if (!key) continue;
      const [r, g, b] = colors[key];
      const i = (y * SPRITE_W + x) * 4;
      data[i] = r; data[i + 1] = g; data[i + 2] = b; data[i + 3] = 255;
    }
  }
  return data;
}

function hex(c: string): [number, number, number] {
  return [parseInt(c.slice(1, 3), 16), parseInt(c.slice(3, 5), 16), parseInt(c.slice(5, 7), 16)];
}
