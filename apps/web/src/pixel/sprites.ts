/**
 * Pixel sprites authored as string matrices — no binary assets.
 * Chars map to palette keys: S skin, R robe, A accent, D dark, W white.
 * A fighter sprite = shared pose body (16×24) + look overlay (head rows
 * 0–7: beard/wig/accessory) recolored by the roster palette.
 */

export type Palette = { skin: string; robe: string; accent: string; dark?: string };

const CHAR_MAP: Record<string, keyof Required<Palette> | null> = {
  '.': null,
  S: 'skin',
  R: 'robe',
  A: 'accent',
  D: 'dark',
  W: 'accent', // white detail → accent by default
};

